var realPerpetuals = market.Perpetuals

const day = int64(1_791_590_400_000) - int64(1_791_590_400_000)%market.DayMS
const hourMS = int64(3_600_000)

func noNetwork(t *testing.T) {
	old := market.Perpetuals
	market.Perpetuals = func() ([]market.Symbol, error) { return nil, nil }
	t.Cleanup(func() { market.Perpetuals = old })
}

func mkt(f8, perp, basis float64, young bool, range14 float64) *MarketData {
	var f []F8Row
	for j := int64(0); j < 9; j++ {
		f = append(f, F8Row{Time: day - 3*market.DayMS + j*8*hourMS, Rate: f8, F8: f8})
	}
	first := day - 30*market.DayMS
	if young {
		first = day - 2*market.DayMS
	}
	return &MarketData{PerpOpen: perp, SpotOpen: perp / (1 + basis), Range14: range14, F8: f, SpotFirst: first}
}

func heldOf(kv ...any) state.HeldMap {
	var h state.HeldMap
	for i := 0; i < len(kv); i += 2 {
		h.Set(kv[i].(string), kv[i+1].(*state.Held))
	}
	return h
}

func hp(n float64) *state.Held { return &state.Held{N: n, Ref: 10, Perp0: 10, Spot0: 10} }

func eq(t *testing.T, got, want []string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("got %v want %v", got, want)
	}
	for i := range got {
		if got[i] != want[i] {
			t.Fatalf("got %v want %v", got, want)
		}
	}
}

func TestOpensAboveThresholdOnly(t *testing.T) {
	noNetwork(t)
	mk := map[string]*MarketData{"AUSDT": mkt(0.0003, 10, 0, false, 0.1), "BUSDT": mkt(0.00015, 10, 0, false, 0.1)}
	p, err := Decide(day, state.HeldMap{}, 600, []string{"AUSDT", "BUSDT"}, mk, nil)
	if err != nil {
		t.Fatal(err)
	}
	eq(t, p.Book, []string{"AUSDT"})
	eq(t, p.Open, []string{"AUSDT"})
	if !testutil.Close(p.Notional["AUSDT"], 100, 1e-6) {
		t.Fatal(p.Notional)
	}
}

