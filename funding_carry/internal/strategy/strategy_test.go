func ff(x float64) string { return strconv.FormatFloat(x, 'g', -1, 64) }

func TestDecideFetchedMarketsMatchPython(t *testing.T) {
	var fx fetchFixture
	testutil.Load(t, "decide_fetch", &fx)
	market.Perpetuals = realPerpetuals
	oldF, oldS, oldSleep := market.FAPI, market.SPOT, market.Sleep
	market.Sleep = func(time.Duration) {}
	t.Cleanup(func() { market.FAPI, market.SPOT, market.Sleep = oldF, oldS, oldSleep; market.ResetCache() })
	cur := 0
	ts := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		c := fx.Cases[cur]
		q := r.URL.Query()
		lo, _ := strconv.ParseInt(q.Get("startTime"), 10, 64)
		hi, _ := strconv.ParseInt(q.Get("endTime"), 10, 64)
		d := fx.D0 + c.Day
		sym := q.Get("symbol")
		var out []any
		switch r.URL.Path {
		case "/fapi/v1/klines":
			for _, k := range c.Data[sym].K {
				ot := fx.D0 + int64(k[0])
				if ot >= lo && ot <= hi {
					out = append(out, []any{ot, ff(k[1]), ff(k[2]), ff(k[3]), ff(k[4]), "10", ot + market.DayMS - 1, "1000", 5, "1", "1", "0"})
				}
			}
		case "/api/v3/klines":
			for _, k := range c.Data[sym].S {
				ot := fx.D0 + int64(k[0])
				if ot >= lo && ot <= hi {
					out = append(out, []any{ot, ff(k[1]), ff(k[1]), ff(k[1]), ff(k[1]), "10", ot + market.DayMS - 1, "1000", 5, "1", "1", "0"})
				}
			}
		case "/fapi/v1/fundingRate":
			for _, k := range c.Data[sym].F {
				ot := fx.D0 + int64(k[0])
				if ot >= lo && ot <= hi {
					out = append(out, map[string]any{"symbol": sym, "fundingTime": ot, "fundingRate": ff(k[1]), "markPrice": "1.0"})
				}
			}
		case "/fapi/v1/exchangeInfo":
			var syms []any
			for s, dd := range c.DD {
				e := map[string]any{"symbol": s, "status": "TRADING", "contractType": "PERPETUAL", "quoteAsset": "USDT",
					"filters": []any{map[string]any{"filterType": "PRICE_FILTER", "tickSize": "0.1", "x": 1}}}
				if dd != nil {
					e["deliveryDate"] = fx.D0 + *dd
				}
				syms = append(syms, e)
			}
			syms = append(syms, map[string]any{"symbol": "QQQ", "status": "TRADING", "contractType": "CURRENT_QUARTER", "quoteAsset": "USDT"})
			json.NewEncoder(w).Encode(map[string]any{"timezone": "UTC", "symbols": syms})
			return
		default:
			t.Errorf("unexpected path %s (day %d)", r.URL.Path, d)
		}
		if out == nil {
			out = []any{}
		}
		json.NewEncoder(w).Encode(out)
	}))
	defer ts.Close()
	market.FAPI, market.SPOT = ts.URL, ts.URL
	for i, c := range fx.Cases {
		cur = i
		market.ResetCache()
		plan, err := Decide(fx.D0+c.Day, c.Held.Clone(), c.Equity, c.Cands, nil, map[string]int64{})
		if err != nil {
			t.Fatalf("case %d: %v", i, err)
		}
		if df := testutil.Diff(any(c.Exp), any(planJSON(t, plan, nil, true)), 1e-9); df != "" {
			t.Fatalf("case %d: %s", i, df)
		}
	}
	t.Logf("decide with fetched markets (klines, funding, spot opens, delisting): %d cases equal", len(fx.Cases))
}
